// ตัวอย่างที่ 1: for loop ธรรมดา

// ใช้วนลูปแสดงเลข 0 ถึง 5
// เริ่มจาก i = 0 และทำงานต่อไปจนกว่า i จะมากกว่า 5
for (var i = 0; i <= 5; i++) {
    // แสดงค่าของ i ในแต่ละรอบ
    console.log(i);
}

// ---------------------------------------------------------

// ตัวอย่างที่ 2: แสดงข้อมูลรถที่อยู่ในบริษัท

// สร้างอาเรย์เก็บชื่อรถหลายคัน
var cars = ["BMW", "Ford", "Honda", "Audi"];

// ใช้ for loop เพื่อแสดงชื่อรถแต่ละคันจากอาเรย์
for (var i = 0; i < cars.length; i++) {
    // แสดงชื่อรถตามตำแหน่งในอาเรย์ (index)
    console.log(cars[i]);
}

// ---------------------------------------------------------

// ตัวอย่างที่ 3: for...in กับ Object

// สร้างอ็อบเจกต์เก็บข้อมูลของบุคคล
var person = {
    fname: "Pilan",   // ชื่อ
    lname: "Kasorn",  // นามสกุล
    age: 18           // อายุ
};

// ใช้ for...in เพื่อวนลูปดู key ทั้งหมดในอ็อบเจกต์
var x;
for (x in person) {
    // แสดงค่าของแต่ละ key (เช่น ชื่อ นามสกุล อายุ)
    console.log(person[x]);
}

// ---------------------------------------------------------

// ตัวอย่างที่ 4: for...of กับอาเรย์

// อาเรย์เก็บชื่อรถ (เวอร์ชันที่ไม่มี Audi)
var cars = ["BMW", "Ford", "Honda"];

// ใช้ for...of เพื่อแสดงค่าทุกตัวในอาเรย์โดยไม่ต้องใช้ index
for (var x of cars) {
    // แสดงชื่อรถในแต่ละรอบ
    console.log(x);
}

// ---------------------------------------------------------

// ตัวอย่างที่ 5: for...of กับข้อความ

// ประกาศตัวแปรเป็นข้อความ (string)
var myString = "Hello";

// ใช้ for...of เพื่อวนดูตัวอักษรแต่ละตัวในข้อความ
var y;
for (y of myString) {
    // แสดงตัวอักษรทีละตัว เช่น H, e, l, l, o
    console.log(y);
}
